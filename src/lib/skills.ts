export function skillPrompt(ids: string[]): string {
  const active = SKILLS.filter((s) => ids.includes(s.id));
  if (active.length === 0) return "";
  return `\n\n=== مهارات مفعّلة لهذه المحادثة (التزم بها حرفياً) ===\n${active
    .map((s) => s.prompt)
    .join("\n\n")}`;
}

export function useSkills() {
  const [skills, setSkillsState] = useState<string[]>([]);

  useEffect(() => {
    try {
      const raw = window.localStorage.getItem(SKILLS_STORAGE_KEY);
      if (raw) setSkillsState(JSON.parse(raw) as string[]);
    } catch {
      /* تجاهل */
    }
  }, []);

  const setSkills = useCallback((next: string[]) => {
    setSkillsState(next);
    window.localStorage.setItem(SKILLS_STORAGE_KEY, JSON.stringify(next));
  }, []);

  const toggle = useCallback(
    (id: string) =>
      setSkillsState((prev) => {
        const next = prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id];
        window.localStorage.setItem(SKILLS_STORAGE_KEY, JSON.stringify(next));
        return next;
      }),
    [],
  );

  return { skills, setSkills, toggle };
}
